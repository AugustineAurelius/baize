local function map(lhs, rhs, desc)
  vim.keymap.set("n", lhs, rhs, { buffer = true, desc = desc })
end
map("gd", vim.lsp.buf.definition, "Rust: definition")
map("gr", vim.lsp.buf.references, "Rust: references")
map("K", function() vim.cmd.RustLsp { "hover", "actions" } end, "Rust: documentation")
map("<leader>ca", function() vim.cmd.RustLsp "codeAction" end, "Rust: code action")
map("<leader>rr", function() vim.cmd.RustLsp "runnables" end, "Rust: run target")
map("<leader>rt", function() vim.cmd.RustLsp "testables" end, "Rust: tests")
map("<leader>rd", function() vim.cmd.RustLsp "debuggables" end, "Rust: debug target")
map("<leader>rm", function() vim.cmd.RustLsp "expandMacro" end, "Rust: expand macro")
map("<leader>re", function() vim.cmd.RustLsp "explainError" end, "Rust: explain error")
map("<leader>rh", function()
  vim.lsp.inlay_hint.enable(not vim.lsp.inlay_hint.is_enabled { bufnr = 0 }, { bufnr = 0 })
end, "Rust: toggle inlay hints")
